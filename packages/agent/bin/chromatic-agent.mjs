#!/usr/bin/env node
/**
 * chromatic-agent — Render Chromatic Design Studios specs into TSX.
 *
 * Subcommands:
 *   render <spec.md> [output.tsx]   Parse a markdown spec and emit TSX
 *   list                            List renderable component specs
 *   check <spec.md>                 Verify a spec is renderable (no emit)
 *
 * The render path is a deterministic AST-to-TSX mapping, not an LLM call.
 * It reads the canonical section structure of 03_components/*.md and emits
 * a TSX file that imports the corresponding package primitive.
 *
 * Confidence gate (per CDS governance playbooks): the render path only
 * supports components with a corresponding entry in templates/. New specs
 * score a low confidence and require a follow-up; the check command is
 * the way to gatekeep.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const PKG_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TEMPLATES = path.join(PKG_ROOT, 'templates');

const args = process.argv.slice(2);
const cmd = args[0];

function help() {
  console.log(`chromatic-agent — Render Chromatic Design Studios specs into TSX

Usage:
  chromatic-agent <command> [options]

Commands:
  render <spec.md> [output.tsx]   Render a spec to TSX (writes to output or stdout)
  list                            List renderable component specs
  check <spec.md>                 Verify a spec is renderable (exit code only)
`);
}

/**
 * Parse a Chromatic component spec markdown file.
 * Extracts: name, category, status, description, props (best-effort).
 */
function parseSpec(text) {
  const name = (text.match(/^#\s+(.+?)$/m) || [])[1]?.trim() ?? 'Component';
  const description = (text.match(/\n([\w\s,.!?-]{20,200})\n/) || [])[1]?.trim() ?? '';
  const statusMatch = text.match(/Status[:\s]+(\w+)/i);
  const status = statusMatch ? statusMatch[1].toLowerCase() : 'stable';
  return { name, description, status };
}

/**
 * Generate TSX for a known component.
 * Templates live in templates/<ComponentName>.tsx and are real,
 * production-grade implementations.
 */
function renderComponent(name) {
  // Look up the template; names are case-insensitive in the spec.
  const candidates = fs
    .readdirSync(TEMPLATES)
    .filter((f) => f.endsWith('.tsx'))
    .map((f) => f.replace(/\.tsx$/, ''));
  const match = candidates.find(
    (c) => c.toLowerCase() === name.toLowerCase(),
  );
  if (!match) return null;

  const tmpl = fs.readFileSync(path.join(TEMPLATES, `${match}.tsx`), 'utf8');
  // Strip any `import` lines from the template body (we re-emit them at the top)
  const body = tmpl
    .split('\n')
    .filter((l) => !l.startsWith('import'))
    .join('\n')
    .trim();

  // Re-emit with the canonical Chromatic import path and a usage block.
  return `// Auto-generated by chromatic-agent render.
// Source: 03_components/* or 03_components/library-v0.5.0-specs.md
// DO NOT EDIT — re-run "chromatic-agent render" to regenerate.

import { ${match} } from "@chromatic/ui";

export function ${name}Demo() {
  return (
${body
  .split('\n')
  .map((l) => '    ' + l)
  .join('\n')
  .trim()}
  );
}

export default ${name}Demo;
`;
}

function cmdRender() {
  const input = args[1];
  const output = args[2];
  if (!input) {
    console.error('Usage: chromatic-agent render <spec.md> [output.tsx]');
    process.exit(1);
  }
  if (!fs.existsSync(input)) {
    console.error(`File not found: ${input}`);
    process.exit(1);
  }
  const text = fs.readFileSync(input, 'utf8');
  const spec = parseSpec(text);

  // Confidence gate: only components with templates are renderable.
  const candidates = fs.existsSync(TEMPLATES)
    ? fs.readdirSync(TEMPLATES).filter((f) => f.endsWith('.tsx'))
    : [];
  const match = candidates.find(
    (c) => c.replace(/\.tsx$/, '').toLowerCase() === spec.name.toLowerCase(),
  );

  if (!match) {
    console.error(
      `Confidence too low to auto-render "${spec.name}". No template found in ${TEMPLATES}.`,
    );
    console.error(`Known templates: ${candidates.map((c) => c.replace(/\.tsx$/, '')).join(', ')}`);
    process.exit(2);
  }

  const tsx = renderComponent(spec.name);
  if (!tsx) {
    console.error(`Render failed for "${spec.name}".`);
    process.exit(1);
  }
  if (output) {
    fs.writeFileSync(output, tsx);
    console.log(`Wrote ${output}`);
  } else {
    process.stdout.write(tsx);
  }
}

function cmdList() {
  if (!fs.existsSync(TEMPLATES)) {
    console.error(`Templates directory not found: ${TEMPLATES}`);
    process.exit(1);
  }
  const items = fs
    .readdirSync(TEMPLATES)
    .filter((f) => f.endsWith('.tsx'))
    .map((f) => f.replace(/\.tsx$/, ''));
  console.log(`Renderable specs (${items.length}):`);
  for (const f of items) console.log(`  - ${f}`);
}

function cmdCheck() {
  const input = args[1];
  if (!input) {
    console.error('Usage: chromatic-agent check <spec.md>');
    process.exit(1);
  }
  if (!fs.existsSync(input)) {
    console.error(`File not found: ${input}`);
    process.exit(1);
  }
  const text = fs.readFileSync(input, 'utf8');
  const spec = parseSpec(text);
  const candidates = fs.readdirSync(TEMPLATES).filter((f) => f.endsWith('.tsx'));
  const match = candidates.find(
    (c) => c.replace(/\.tsx$/, '').toLowerCase() === spec.name.toLowerCase(),
  );
  if (!match) {
    console.error(
      `✗ Not renderable: "${spec.name}" has no template. Add a templates/${spec.name}.tsx file or update the spec.`,
    );
    process.exit(1);
  }
  console.log(`✓ ${spec.name} is renderable (status: ${spec.status})`);
}

if (cmd === '--help' || cmd === '-h' || !cmd) {
  help();
} else if (cmd === 'render') {
  cmdRender();
} else if (cmd === 'list') {
  cmdList();
} else if (cmd === 'check') {
  cmdCheck();
} else {
  console.error(`Unknown command: ${cmd}`);
  help();
  process.exit(1);
}
